/**
 * Audit helper verifying that each product's currentStock strictly equals
 * the runningBalance of its latest stock movement entry.
 */
export function verifySeedIntegrity(): { valid: boolean; mismatches: string[] } {
  const mismatches: string[] = [];

  SEED_PRODUCTS.forEach((product) => {
    // Find the latest movement for this product
    const productMovements = SEED_STOCK_MOVEMENTS.filter((m) => m.productId === product.id);
    if (productMovements.length === 0) {
      mismatches.push(`No movements for ${product.sku}`);
      return;
    }
    const latest = productMovements[0]; // Since reversed, index 0 is most recent
    if (latest.runningBalance !== product.currentStock) {
      mismatches.push(
        `${product.sku} (${product.name}): currentStock=${product.currentStock} != latestRunningBalance=${latest.runningBalance}`
      );
    }
  });

  return {
    valid: mismatches.length === 0,
    mismatches,
  };
}
